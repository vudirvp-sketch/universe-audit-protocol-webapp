function nonEmpty(value?: string): string | null {
  const trimmed = value?.trim();
  return trimmed ? trimmed : null;
}

/** Render the guided-mode framing supplied by the author (v16 §2). */
export function buildGuidedContextBlock(guided?: GuidedContext): string {
  if (!guided) return '';

  const lines: string[] = [];
  for (const field of GUIDED_FIELDS) {
    const value = nonEmpty(guided[field.key]);
    if (value) lines.push(`${field.label}: ${value}`);
  }
  if (lines.length === 0) return '';

  return `РАМКИ АВТОРА — РЕЖИМ guided (заданы автором, а не выведены аудитором):
${lines.join('\n')}

Как использовать рамки: они меняют ВЕС и применимость разделов, но не снижают причинный стандарт. Заявленная рамка не является доказательством её выполнения — если материал ей противоречит, зафиксируй противоречие. Исключённые вопросы не открывай; если они скрывают причинный дефект, скажи об этом одной строкой и не разворачивай.`;
}

/** Render the additional artefacts supplied for material-aware mode (v16 §2). */
export function buildMaterialsBlock(materials?: AuditMaterial[]): string {
  const usable = (materials ?? []).filter((material) => nonEmpty(material.text));
  if (usable.length === 0) return '';

  const blocks = usable.map((material, index) => {
    const label = nonEmpty(material.label) ?? `Артефакт ${index + 1}`;
    return `[Артефакт ${index + 1}: «${label}»]\n${material.text.trim()}`;
  });

  return `ДОПОЛНИТЕЛЬНЫЕ МАТЕРИАЛЫ — слои доказательств (режим material_aware при двух и более артефактах):
${blocks.join('\n\n')}

ПРАВИЛА РАБОТЫ С НЕСКОЛЬКИМИ АРТЕФАКТАМИ:
- считай артефакты разными слоями доказательств (концепт, манускрипт, дизайн-документ, лор-библия, таблицы, карты, код), а не дублями одного текста;
- при расхождении источников: зафиксируй расхождение, укажи, какой источник выглядит каноническим, не примиряй противоречие молча и оцени его последствия;
- молчание одного артефакта не означает отсутствия элемента в мире: различай «нет в материале» и «противоречит материалу»;
- когда источники расходятся, привязывай утверждение к конкретному артефакту.`;
}

/** Combined guided framing + additional artefacts block injected into every prompt. */
export function buildExtraContextBlock(input: Pick<AuditInput, 'guided' | 'materials'>): string {
  return [buildGuidedContextBlock(input.guided), buildMaterialsBlock(input.materials)]
    .filter(Boolean)
    .join('\n\n');
}

